"""Huginn benchmark — local backend, now a repeatable gate (RM-005).

Run: python scripts/benchmark.py [--check | --update-baseline | --no-check]

What it does:
- Runs the headline operations below on a fresh temporary local
  store, at the workload sizes in ``WORKLOAD`` (overridable).
- Prints a text summary and a JSON record. Every record carries an
  environment block (machine, CPU count, load average, Python and
  SQLite versions) so a number is never quoted without the machine
  and load it was measured under (RM-005/RM-006 honesty rule).
- Gate mode (the default when a baseline exists): compares each
  headline operation against ``baseline.json`` beside this script
  and exits 1 if any operation regressed by more than the
  threshold (default 25%).
- ``--update-baseline`` re-records ``baseline.json`` from this run.
  Re-baselining is a deliberate act: do it only when a change is
  understood, never to silence a regression you have not read.

Class: BENCH. Numbers on a loaded machine are indicative, not
absolutes — the environment block in every record says so. This
benchmark covers the local backend only; a live Qdrant round-trip
stays NOT PROVEN until actually run against a server.

Corpus (RM-020): the stored documents are generated by
``doc_text()`` — a pure formula of the index, no randomness
anywhere — and versioned as ``CORPUS_VERSION`` (the fixed search
queries are part of the versioned corpus definition). Every
record carries the corpus block (version, count, SHA-256 of the
documents) in its details and in the printed output, and the
gate refuses to compare timings across a different corpus:
BENCH numbers only ever compare like with like.
"""

import argparse
import hashlib
import json
import os
import platform
import sqlite3
import statistics
import sys
import tempfile
import time
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

DEFAULT_THRESHOLD = 0.25
BASELINE_PATH = Path(__file__).resolve().parent / "baseline.json"

WORKLOAD = {
    "n_docs": 5000,
    "n_search": 200,
    "n_search_filtered": 100,
}

# Headline operations, in run order. These keys are the gate's
# contract: a baseline missing one, or a run missing one, fails.
HEADLINE_OPS = (
    "upsert",
    "search",
    "search_filtered",
)

WORDS = [
    "raven", "wolf", "river", "stone", "fire", "ice", "saga", "rune",
    "ship", "sea", "storm", "wolf", "memory", "thought", "wisdom", "eye",
    "well", "tree", "root", "branch", "leaf", "song", "sword",
]


def doc_text(i):
    words = [WORDS[(i * 7 + j * 3) % len(WORDS)] for j in range(24)]
    return " ".join(words)


# Corpus version (RM-020). Bump this whenever doc_text, WORDS or
# the fixed search queries change shape, so records made under
# different corpora are never compared as if equal.
CORPUS_VERSION = 1


def corpus_texts(n):
    return [doc_text(i) for i in range(n)]


def corpus_block(texts):
    """Version + count + SHA-256 over the texts (each encoded
    UTF-8 and newline-terminated, in order)."""
    digest = hashlib.sha256()
    for text in texts:
        digest.update(text.encode("utf-8"))
        digest.update(b"\n")
    return {
        "version": CORPUS_VERSION,
        "count": len(texts),
        "sha256": digest.hexdigest(),
    }


def environment_block():
    """Machine + load labelling for every benchmark record."""
    try:
        load = list(os.getloadavg())
    except (AttributeError, OSError):
        load = None
    return {
        "recorded_at": datetime.now(UTC).isoformat(),
        "machine": platform.machine(),
        "system": platform.system(),
        "platform": platform.platform(),
        "node": platform.node(),
        "cpu_count": os.cpu_count(),
        "load_avg": load,
        "python_version": platform.python_version(),
        "sqlite_version": sqlite3.sqlite_version,
    }


def compare_to_baseline(current, baseline, threshold=DEFAULT_THRESHOLD):
    """Return a list of regression dicts; empty list means the gate passes.

    ``current`` and ``baseline`` map headline op -> ms (upsert: total
    ms for the batch; search ops: median ms per search). A
    regression is a current value more than ``threshold`` (a
    fraction, default 0.25) above its baseline. A headline op
    missing from either side is reported as a regression with
    ``reason: "missing"`` — a silent gap must never pass the gate.
    """
    regressions = []
    for op in HEADLINE_OPS:
        if op not in baseline:
            regressions.append(
                {"operation": op, "reason": "missing_from_baseline"}
            )
            continue
        if op not in current:
            regressions.append(
                {"operation": op, "reason": "missing_from_current"}
            )
            continue
        base = float(baseline[op])
        cur = float(current[op])
        change = (cur - base) / base if base > 0 else (0.0 if cur == 0 else float("inf"))
        if change > threshold:
            regressions.append(
                {
                    "operation": op,
                    "baseline_ms": base,
                    "current_ms": cur,
                    "regression": change,
                    "threshold": threshold,
                }
            )
    return regressions


def run_benchmark(workload):
    """Run the headline operations; return (results_ms, details)."""
    # Imported here, after the sys.path bootstrap above, so the script
    # also runs from a bare checkout with nothing installed.
    from huginn import HuginnConfig, HuginnMemory

    tmp = tempfile.mkdtemp(prefix="huginn-bench-")
    h = HuginnMemory(
        HuginnConfig(backend="local", local_db_path=str(Path(tmp) / "bench.db"))
    )
    n_docs = workload["n_docs"]
    results = {}

    texts = corpus_texts(n_docs)
    start = time.perf_counter()
    for i, text in enumerate(texts):
        h.upsert_memory(content=text, category=f"cat{i % 10}", importance=5)
    elapsed_ms = (time.perf_counter() - start) * 1000
    results["upsert"] = elapsed_ms
    print(f"upsert_memory() x{n_docs} docs           {elapsed_ms:10.1f} ms total"
          f"  ({elapsed_ms / n_docs:.2f} ms/doc)")

    queries = ["raven wisdom tree", "sword fire storm", "ship sea song", "wolf eye memory"]

    def _search_median(n, **kwargs):
        times = []
        for i in range(n):
            q = queries[i % len(queries)]
            start = time.perf_counter()
            h.search(query_text=q, limit=10, **kwargs)
            times.append((time.perf_counter() - start) * 1000)
        times.sort()
        return statistics.median(times), times[int(len(times) * 0.95)]

    median, p95 = _search_median(workload["n_search"])
    results["search"] = median
    print(f"search(limit=10) over {n_docs} docs      median {median:8.2f} ms"
          f"  p95 {p95:8.2f} ms")

    median_f, p95_f = _search_median(
        workload["n_search_filtered"], category="cat3"
    )
    results["search_filtered"] = median_f
    print(f"search(category filter)                 median {median_f:8.2f} ms"
          f"  p95 {p95_f:8.2f} ms")
    h.close()
    details = {
        "workload": dict(workload),
        "unit": "upsert: total ms for the batch; search ops: median ms per search",
        "search_p95_ms": {"search": p95, "search_filtered": p95_f},
        "backend": "local",
        "corpus": corpus_block(texts),
    }
    return results, details


def build_record(results, details, threshold):
    return {
        "package": "huginn",
        "schema": 1,
        "threshold": threshold,
        "environment": environment_block(),
        "results_ms": results,
        "details": details,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=None,
                        help="write the JSON record to this path")
    parser.add_argument("--baseline", type=Path, default=BASELINE_PATH)
    parser.add_argument("--threshold", type=float, default=None,
                        help="regression fraction (default: baseline's, else 0.25)")
    parser.add_argument("--update-baseline", action="store_true")
    parser.add_argument("--no-check", action="store_true",
                        help="measure only; do not compare against the baseline")
    parser.add_argument("--docs", type=int, default=WORKLOAD["n_docs"])
    args = parser.parse_args(argv)

    workload = dict(WORKLOAD, n_docs=args.docs)
    results, details = run_benchmark(workload)

    baseline_record = None
    if args.baseline.exists():
        baseline_record = json.loads(args.baseline.read_text())
    if args.threshold is not None:
        threshold = args.threshold
    elif baseline_record is not None:
        threshold = float(baseline_record.get("threshold", DEFAULT_THRESHOLD))
    else:
        threshold = DEFAULT_THRESHOLD

    record = build_record(results, details, threshold)
    env = record["environment"]
    print("environment:")
    for key in (
        "recorded_at", "machine", "system", "platform", "node",
        "cpu_count", "load_avg", "python_version", "sqlite_version",
    ):
        print(f"  {key}: {env[key]}")
    corpus = record["details"]["corpus"]
    print("corpus:")
    print(f"  version: {corpus['version']}")
    print(f"  count: {corpus['count']}")
    print(f"  sha256: {corpus['sha256']}")
    if args.output is not None:
        args.output.write_text(json.dumps(record, indent=2) + "\n")
        print(f"record written: {args.output}")

    if args.update_baseline:
        args.baseline.write_text(json.dumps(record, indent=2) + "\n")
        print(f"baseline updated: {args.baseline}")
        return 0
    if args.no_check:
        return 0
    if baseline_record is None:
        print(f"GATE: no baseline at {args.baseline}; nothing to check against")
        return 0
    regressions = compare_to_baseline(
        results, baseline_record.get("results_ms", {}), threshold
    )
    corpus_fail = False
    baseline_corpus = baseline_record.get("details", {}).get("corpus")
    if baseline_corpus is None:
        print("GATE NOTE: baseline predates corpus versioning (RM-020); "
              "timing comparison only")
    elif baseline_corpus != corpus:
        corpus_fail = True
        print(
            "GATE FAIL: corpus mismatch — baseline "
            f"v{baseline_corpus.get('version')} "
            f"{baseline_corpus.get('sha256')} (n={baseline_corpus.get('count')})"
            f" vs current v{corpus['version']} {corpus['sha256']} "
            f"(n={corpus['count']}); timings across corpora are not comparable"
        )
    if regressions:
        for r in regressions:
            if r.get("reason"):
                print(f"GATE FAIL: {r['operation']}: {r['reason']}")
            else:
                print(
                    f"GATE FAIL: {r['operation']}: {r['baseline_ms']:.2f} ms -> "
                    f"{r['current_ms']:.2f} ms "
                    f"(+{r['regression'] * 100:.1f}% > {threshold * 100:.0f}%)"
                )
        return 1
    if corpus_fail:
        return 1
    print(f"GATE PASS: no headline operation regressed > {threshold * 100:.0f}%")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
