"""RM-020 — Reproducible benchmark corpus for huginn.

The benchmark corpus is generated by a pure formula of the
index (``doc_text`` / ``corpus_texts`` in scripts/benchmark.py):
no randomness anywhere, so two runs on any machine store
byte-identical documents. Every benchmark record carries the
corpus block — version, count, SHA-256 — and these tests pin
that:

* the generator is deterministic and the block's hash is an
  honest recomputation over the generated documents;
* the committed baseline carries the corpus block for the
  default workload, so gate comparisons are like-with-like;
* the real script, run at a tiny workload, records the corpus
  hash in BOTH its printed output and its JSON record, and
  two runs record the same hash.
"""

import hashlib
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

SCRIPTS = Path(__file__).parent.parent / "scripts"


def _load_benchmark_module():
    spec = importlib.util.spec_from_file_location(
        "huginn_benchmark_corpus", SCRIPTS / "benchmark.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


bench = _load_benchmark_module()


def _expected_block(n):
    digest = hashlib.sha256()
    for text in bench.corpus_texts(n):
        digest.update(text.encode("utf-8"))
        digest.update(b"\n")
    return {"version": bench.CORPUS_VERSION, "count": n, "sha256": digest.hexdigest()}


def test_corpus_generation_is_deterministic():
    assert bench.corpus_texts(50) == bench.corpus_texts(50)
    assert bench.corpus_texts(7) == [bench.doc_text(i) for i in range(7)]


def test_corpus_block_hash_is_an_honest_recomputation():
    assert bench.corpus_block(bench.corpus_texts(50)) == _expected_block(50)
    # A different workload size is a different corpus.
    assert bench.corpus_block(bench.corpus_texts(51)) != _expected_block(50)


def test_committed_baseline_carries_the_default_corpus():
    baseline = json.loads((SCRIPTS / "baseline.json").read_text())
    n = baseline["details"]["workload"]["n_docs"]
    assert baseline["details"]["corpus"] == _expected_block(n)


def _run_benchmark(tmp_path, name):
    out_json = tmp_path / name
    proc = subprocess.run(
        [
            sys.executable,
            str(SCRIPTS / "benchmark.py"),
            "--docs", "20",
            "--no-check",
            "--output", str(out_json),
        ],
        capture_output=True,
        text=True,
        timeout=180,
    )
    assert proc.returncode == 0, proc.stderr
    return proc.stdout, json.loads(out_json.read_text())


def test_benchmark_output_records_corpus_hash(tmp_path):
    expected = _expected_block(20)
    stdout, record = _run_benchmark(tmp_path, "a.json")
    assert record["details"]["corpus"] == expected
    assert "corpus:" in stdout
    assert f"sha256: {expected['sha256']}" in stdout
    # A second run records the identical hash — reproducibility.
    _, record_b = _run_benchmark(tmp_path, "b.json")
    assert record_b["details"]["corpus"] == expected
